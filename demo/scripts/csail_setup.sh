#!/usr/bin/env bash
# One-shot setup for the findit demo on a CSAIL GPU host (e.g. mapmaker-gpu2).
# Idempotent: safe to re-run. Does not need root.
#
#   cd findit/demo && bash scripts/csail_setup.sh
#
# Env overrides:
#   FINDIT_VENV       venv path          (default: ./.venv)
#   HF_HOME           Hugging Face cache (default: /scratch/$USER/hf if /scratch is writable, else ~/.cache/huggingface)
#   FINDIT_VLM_MODEL  VLM to pre-download (default chosen from GPU memory)
#   FINDIT_API_PORT / FINDIT_VLM_PORT   (default 8000 / 8001)
set -euo pipefail
cd "$(dirname "$0")/.."

VENV="${FINDIT_VENV:-./.venv}"

# --- GPU check ------------------------------------------------------------
if ! command -v nvidia-smi >/dev/null; then
  echo "nvidia-smi not found: this script expects an NVIDIA GPU host." >&2; exit 1
fi
nvidia-smi --query-gpu=name,memory.total,memory.used --format=csv
VRAM_MB=$(nvidia-smi --query-gpu=memory.total --format=csv,noheader,nounits | sort -n | tail -1)
if [ -z "${FINDIT_VLM_MODEL:-}" ]; then
  if [ "$VRAM_MB" -ge 14000 ]; then FINDIT_VLM_MODEL="Qwen/Qwen3-VL-4B-Instruct"; else FINDIT_VLM_MODEL="Qwen/Qwen3-VL-2B-Instruct"; fi
fi
echo "VLM: $FINDIT_VLM_MODEL"

# --- model cache location (home dirs at CSAIL are often quota-limited) ------
if [ -z "${HF_HOME:-}" ] && [ -d /scratch ] && [ -w /scratch ]; then
  export HF_HOME="/scratch/$USER/hf"
fi
export HF_HOME="${HF_HOME:-$HOME/.cache/huggingface}"
mkdir -p "$HF_HOME"
echo "HF cache: $HF_HOME"

# --- python env -------------------------------------------------------------
PY=$(command -v python3.12 || command -v python3.11 || command -v python3.10 || command -v python3)
echo "python: $PY ($("$PY" --version))"
[ -d "$VENV" ] || "$PY" -m venv "$VENV"
# shellcheck disable=SC1091
. "$VENV/bin/activate"
pip install -q --upgrade pip
pip install -q -r requirements.txt
pip install -q torch torchvision transformers pillow accelerate huggingface_hub
# vLLM ships CUDA 12 wheels and needs a reasonably recent driver.
pip install -q vllm || echo "WARNING: vllm install failed. Use llama.cpp's llama-server instead (see README)."

# --- pre-download models so the first run is not a long wait ---------------
FINDIT_VLM_MODEL="$FINDIT_VLM_MODEL" python - <<'PYEOF'
import os
from huggingface_hub import snapshot_download
for repo in ["google/owlv2-base-patch16-ensemble", "google/siglip2-base-patch16-224", os.environ["FINDIT_VLM_MODEL"]]:
    print("fetching", repo)
    snapshot_download(repo)
PYEOF

cat > .env.csail <<ENV
# generated by scripts/csail_setup.sh
export HF_HOME="$HF_HOME"
export FINDIT_VENV="$VENV"
export FINDIT_VLM_MODEL="$FINDIT_VLM_MODEL"
export FINDIT_DETECTOR=owlv2
export FINDIT_EMBEDDER=siglip2
export FINDIT_API_PORT=${FINDIT_API_PORT:-8000}
export FINDIT_VLM_PORT=${FINDIT_VLM_PORT:-8001}
export FINDIT_VLM_URL=http://127.0.0.1:${FINDIT_VLM_PORT:-8001}/v1
export FINDIT_DATA_DIR=./data
export FINDIT_VOCAB="sunglasses,glasses,keys,headphones,earbuds,book,scissors,phone,wallet,remote control,mug,bottle,laptop,pen,notebook,hat,bag"
ENV
echo
echo "Setup done. Start with:  bash scripts/csail_run.sh"
